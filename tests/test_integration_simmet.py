"""R-parity integration test: ngs-benchmark detection vs. bmark_stats() on Fosso simmet data.

Golden file generated by tests/scripts/generate_r_golden_simmet.R.
Run that script once from the repo root, then commit the result.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import pytest
from click.testing import CliRunner

from ngs_benchmark.cli import cli

# ---------------------------------------------------------------------------
# Paths — absolute so the test is cwd-independent.
# ---------------------------------------------------------------------------

_REPO = Path(__file__).parents[2]   # EMtrace-benchmark/
_PRED = _REPO / "Legacy/data/LazypipeX.simmet.vi_nt2/abund_table.tsv"
_TRUTH = _REPO / "Legacy/data/2025_10_14.simmet.abund_table.tsv"
_GOLDEN = Path(__file__).parent / "data/golden_r_simmet.tsv"

# Stable output directory for manual inspection after a test run.
_INSPECT_DIR = Path(__file__).parent / "data/simmet_py_out"

_data_available = _PRED.exists() and _TRUTH.exists()
_golden_available = _GOLDEN.exists()

pytestmark = pytest.mark.skipif(
    not (_data_available and _golden_available),
    reason=(
        "Simmet data or R golden file not available. "
        "Run ngs-benchmark/tests/scripts/generate_r_golden_simmet.R from repo root."
    ),
)

_CLI_ARGS = [
    "detection",
    "--pred",     str(_PRED),
    "--truth",    str(_TRUTH),
    "--ranks",    "species,genus,family",
    "--taxgroup", "Viruses,Bacteria",
    "--tail-vi",  "0",
    "--tail-ba",  "0",
    "--read-min", "0",
]


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

def _run_cli(outdir: Path) -> None:
    runner = CliRunner()
    result = runner.invoke(cli, _CLI_ARGS + ["--outdir", str(outdir)])
    assert result.exit_code == 0, result.output


def _load_golden() -> pd.DataFrame:
    """Load R golden TSV; normalise column names for joining."""
    df = pd.read_csv(_GOLDEN, sep="\t")
    # R names the first column after toptaxrank (e.g. "division"); rename to taxgroup.
    first_col = df.columns[0]
    if first_col != "taxgroup":
        df = df.rename(columns={first_col: "taxgroup"})
    # Drop TOTAL aggregate rows — Python does not produce them.
    df = df[~df["taxgroup"].str.upper().str.startswith("TOTAL")]
    return df


# ---------------------------------------------------------------------------
# Tests
# ---------------------------------------------------------------------------

def test_simmet_tp_fp_fn_match_r(tmp_path: Path) -> None:
    """TP/FP/FN counts must be identical to bmark_stats() output."""
    outdir = tmp_path / "out"
    _run_cli(outdir)

    # Also write to stable path for manual inspection.
    _INSPECT_DIR.mkdir(parents=True, exist_ok=True)
    import shutil
    for f in outdir.iterdir():
        shutil.copy(f, _INSPECT_DIR / f.name)

    py = pd.read_csv(outdir / "metrics.tsv", sep="\t")
    golden = _load_golden()

    merged = py.merge(golden, on=["taxgroup", "rank"], suffixes=("_py", "_r"))
    assert len(merged) > 0, "No rows matched between Python and R output"

    for _, row in merged.iterrows():
        label = f"taxgroup={row['taxgroup']} rank={row['rank']}"
        assert int(row["TP_py"]) == int(row["TP_r"]), f"TP mismatch at {label}"
        assert int(row["FP_py"]) == int(row["FP_r"]), f"FP mismatch at {label}"
        assert int(row["FN_py"]) == int(row["FN_r"]), f"FN mismatch at {label}"


def test_simmet_pr_rc_f1_match_r(tmp_path: Path) -> None:
    """Pr/Rc/F1 must agree with bmark_stats() to within 1e-4."""
    outdir = tmp_path / "out"
    _run_cli(outdir)

    py = pd.read_csv(outdir / "metrics.tsv", sep="\t")
    golden = _load_golden()

    merged = py.merge(golden, on=["taxgroup", "rank"], suffixes=("_py", "_r"))

    for _, row in merged.iterrows():
        label = f"taxgroup={row['taxgroup']} rank={row['rank']}"
        assert row["Pr_py"] == pytest.approx(row["Pr_r"], abs=1e-4), f"Pr mismatch at {label}"
        assert row["Rc_py"] == pytest.approx(row["Rc_r"], abs=1e-4), f"Rc mismatch at {label}"
        assert row["F1_py"] == pytest.approx(row["F1_r"], abs=1e-4), f"F1 mismatch at {label}"
